/**
 * v1.3.1: erzeugt die Sperrliste häufiger Passwörter (SPEC 7.2) aus SecLists (MIT-Lizenz,
 * Daniel Miessler). Läuft nur auf dem Entwicklungsrechner; das Ergebnis liegt im Repository:
 *   shared/src/security/common-passwords-data.ts
 * Genommen werden die jeweils ersten 300 000 Einträge von vier öffentlichen Listen (die
 * häufigsten), davon nur Passwörter mit 15 bis 64 Zeichen – kürzere lässt die Mindestlänge ohnehin
 * nicht zu. Gespeichert wird in Kleinschreibung nach NFC, sortiert, ohne Doppelte.
 * Aufruf: node tools/passwords/build.ts
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const CACHE = path.join(import.meta.dirname, '.cache');
const COMMIT = 'a9679c2d7018af36f03ad26b52a8618e2f8057c3';
const BASE = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/Passwords/Common-Credentials`;
const TOP = 300_000;
const MIN = 15;
const MAX = 64;

/** The lists, SHA-256 pinned for reproducibility. */
const SOURCES = [
  {
    file: 'Pwdb_top-1000000.txt',
    sha256: 'e9a88f67aafe65496682dc374559ee714e978bee50314767494c3e37a18c9fc8',
  },
  {
    file: 'xato-net-10-million-passwords-1000000.txt',
    sha256: '424a3e03a17df0a2bc2b3ca749d81b04e79d59cb7aeec8876a5a3f308d0caf51',
  },
  {
    file: '100k-most-used-passwords-NCSC.txt',
    sha256: 'c2e5696882c603b76bb67a47ee970897e5a76fc4c3f5547abe3d0ca340c576e0',
  },
  {
    file: 'Language-Specific/German_common-password-list-top-1000000.txt',
    sha256: '0d8e66c6840202bf85f9510d87447eccaac6784d58b84d38d5b16e69be463416',
  },
];

async function load(source: (typeof SOURCES)[number]): Promise<Buffer> {
  fs.mkdirSync(CACHE, { recursive: true });
  const cached = path.join(CACHE, path.basename(source.file));
  let data = fs.existsSync(cached) ? fs.readFileSync(cached) : null;
  if (!data) {
    const response = await fetch(`${BASE}/${source.file}`);
    if (!response.ok) throw new Error(`${source.file}: HTTP ${response.status}`);
    data = Buffer.from(await response.arrayBuffer());
    fs.writeFileSync(cached, data);
  }
  const hash = crypto.createHash('sha256').update(data).digest('hex');
  if (hash !== source.sha256) throw new Error(`${source.file}: SHA-256 ${hash} passt nicht`);
  return data;
}

const words = new Set<string>();
for (const source of SOURCES) {
  const lines = (await load(source)).toString('utf8').split(/\r?\n/).slice(0, TOP);
  for (const line of lines) {
    const word = line.normalize('NFC').toLowerCase();
    const length = [...word].length;
    if (length >= MIN && length <= MAX && !/[\p{Cc}�]/u.test(word)) words.add(word);
  }
}
const sorted = [...words].sort();
const out = `/**
 * v1.3.1: frequently used passwords with 15 to 64 characters (SPEC 7.2), lower case after NFC.
 * Generated by tools/passwords/build.ts from SecLists (commit ${COMMIT.slice(0, 12)}), the first
 * ${TOP.toLocaleString('en')} entries each of: ${SOURCES.map((source) => path.basename(source.file)).join(', ')}.
 * SecLists: Copyright (c) 2018 Daniel Miessler, MIT License (DEPENDENCIES.md).
 * Do not edit by hand.
 */
// prettier-ignore
export const COMMON_PASSWORDS: string = ${JSON.stringify(sorted.join('\n'))};
`;
fs.writeFileSync(path.join(ROOT, 'shared/src/security/common-passwords-data.ts'), out);
console.log(`${sorted.length} Passwörter geschrieben.`);
