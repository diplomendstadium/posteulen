/**
 * Erzeugt shared/src/map/zone-places-data.ts (v1.2.4, SPEC 9.11): zu jeder IANA-Zeitzone den
 * Ort ihrer Hauptstadt (0,1° genau) aus der tz-Datenbank (gemeinfrei) – für Tag und Nacht auf
 * der Startseite ohne Anmeldung nach der Zeitzone des Geräts. Läuft nur auf dem
 * Entwicklungsrechner und liest die tz-Daten des Systems (Debian-Paket tzdata):
 *   zone1970.tab und zone.tab  Koordinaten der Zonen
 *   tzdata.zi                  Verweise alter Namen auf ihre Zone (Zeilen „L Ziel Alias“)
 * Aufruf: node tools/zones/build.ts (danach: npx prettier --write shared/src/map/zone-places-data.ts)
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const TZ = process.env['POSTEULEN_TZDIR'] ?? '/usr/share/zoneinfo';
const OUT = path.join(ROOT, 'shared/src/map/zone-places-data.ts');

/** "+4230+00131" (±DDMM±DDDMM, optional seconds) → [lat, lon] in degrees. */
function coordinates(text: string): [number, number] {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(text);
  if (!match) throw new Error(`unbekannte Koordinate: ${text}`);
  const part = (
    sign: string | undefined,
    d: string | undefined,
    m: string | undefined,
    s?: string,
  ): number => (sign === '-' ? -1 : 1) * (Number(d) + Number(m) / 60 + Number(s ?? 0) / 3600);
  return [
    part(match[1], match[2], match[3], match[4]),
    part(match[5], match[6], match[7], match[8]),
  ];
}

const places = new Map<string, [number, number]>();
for (const file of ['zone1970.tab', 'zone.tab']) {
  for (const line of fs.readFileSync(path.join(TZ, file), 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue;
    const [, coords, zone] = line.split('\t');
    if (!coords || !zone || places.has(zone)) continue;
    places.set(zone, coordinates(coords));
  }
}

const zi = fs.readFileSync(path.join(TZ, 'tzdata.zi'), 'utf8');
const version = /^# version (\S+)/m.exec(zi)?.[1] ?? 'unbekannt';
for (const line of zi.split('\n')) {
  const [kind, target, alias] = line.split(' ');
  if (kind !== 'L' || !target || !alias || places.has(alias)) continue;
  const place = places.get(target);
  if (place) places.set(alias, place);
}

const round = (value: number): number => Math.round(value * 10) / 10;
const entries = [...places.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([zone, [lat, lon]]) => `${zone}:${round(lat)},${round(lon)}`);

fs.writeFileSync(
  OUT,
  `/**
 * Generated by tools/zones/build.ts from the tz database ${version} (public domain) – do not edit.
 * v1.2.4: the place (main city, 0.1°) of every IANA time zone, also under its old names, as
 * "Zone:lat,lon" separated by ";".
 */
// prettier-ignore
export const ZONE_PLACES = ${JSON.stringify(entries.join(';'))};
`,
);
console.log(
  `${entries.length} Zeitzonen (tz ${version}) nach ${path.relative(ROOT, OUT)} geschrieben.`,
);
