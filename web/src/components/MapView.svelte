<script lang="ts">
  /**
   * Political map (SPEC 12) in parchment style – v0.7 of the whole world; registration and
   * moving (`region="europe"`) stay inside the European section where homes are. Zoom and pan with mouse,
   * touch and buttons; tapping reports the geographic position. No tile server, no foreign
   * hosts (SPEC 12.2). Markers, labels and cities are sized in screen pixels, so they stay
   * readable on small screens (v0.2). Cities: from 1 million inhabitants, from 200 000 when
   * zoomed in; their names give way to the user's own places and owls.
   */
  import { onMount, type Snippet } from 'svelte';
  import { i18n, t } from '../lib/i18n.svelte.ts';
  import { MAP } from '@posteulen/shared/constants.ts';
  import {
    CENTRAL_MERIDIAN,
    project,
    projectRelative,
    unproject,
  } from '@posteulen/shared/map/projection.ts';
  import { placeCityLabels, type Box } from '@posteulen/shared/map/labels.ts';
  import { loadMapData, type MapData } from '../lib/map/map-data.ts';
  import { nightRuns } from '../lib/map/night.ts';

  let {
    onpick,
    markers,
    label = t.map.label,
    nightAt = null,
    occupied,
    fit = null,
    region = 'world',
  }: {
    onpick?: (position: { lat: number; lon: number }) => void;
    /** Own markers; `scale` is SVG units per screen pixel. */
    markers?: Snippet<[(lat: number, lon: number) => { x: number; y: number }, number]>;
    label?: string;
    /** Draw night areas for this time (SPEC 12.1); null: no day/night layer. */
    nightAt?: number | null;
    /** Space of the own markers and their names; city names keep clear of it. */
    occupied?: (
      toSvg: (lat: number, lon: number) => { x: number; y: number },
      scale: number,
    ) => Box[];
    /** Zoom once, as soon as possible, so that all these places are just visible (v0.2). */
    fit?: readonly { lat: number; lon: number }[] | null;
    /** v0.7: 'europe' keeps zoom and panning inside the European section (pin picking). */
    region?: 'world' | 'europe';
  } = $props();

  type Frame = readonly [number, number, number, number];
  // Fallback frames until the map data is loaded (as generated by tools/map/build.ts).
  let data = $state<MapData | null>(null);
  let full = $state<Frame>([-17243.9, -8392.9, 34487.9, 16785.8]);
  let europe = $state<Frame>([-1801.6, -6984.6, 3020, 2526]);
  const frame = $derived(region === 'europe' ? europe : full);
  /** Zoom levels (cities, automatic zoom, closest zoom) stay those of the European section. */
  const side = $derived(Math.min(europe[2], europe[3]));
  /**
   * v0.4: the map is always square, and so is the view. In the European section it never shows
   * anything beyond its edge (the largest view is the centred square of the shorter side);
   * v0.7: the whole world fits into the square, with parchment above and below.
   */
  function whole(area: Frame, fitAll: boolean) {
    const size = fitAll ? Math.max(area[2], area[3]) : Math.min(area[2], area[3]);
    return {
      x: area[0] + (area[2] - size) / 2,
      y: area[1] + (area[3] - size) / 2,
      w: size,
      h: size,
    };
  }
  const largest = $derived(whole(frame, region === 'world'));
  /**
   * v0.7.1: the view the map opened with (Western Europe when choosing a home, otherwise the
   * automatic zoom on home, contacts and owls); the reset button goes back to it.
   */
  let initial: { x: number; y: number; w: number; h: number } | null = null;
  let view = $state(whole([-17243.9, -8392.9, 34487.9, 16785.8], true));

  /**
   * v0.4: the square map is as large as fits below its position and above a fixed bottom
   * navigation, so the whole map is visible without scrolling (at least 18rem).
   */
  let wrapper: HTMLDivElement | undefined = $state();
  let maxSide = $state<number | null>(null);
  function measure(): void {
    if (!wrapper) return;
    const top = wrapper.getBoundingClientRect().top + window.scrollY;
    const nav = document.querySelector('[data-bottom-nav]')?.getBoundingClientRect().height ?? 0;
    const rem = parseFloat(getComputedStyle(document.documentElement).fontSize) || 16;
    maxSide = Math.max(18 * rem, window.innerHeight - top - nav - rem);
  }

  // Through the CSSOM, which the CSP allows (no inline style attribute).
  $effect(() => {
    if (wrapper && maxSide !== null) wrapper.style.setProperty('--map-max', `${maxSide}px`);
  });

  onMount(() => {
    measure();
    window.addEventListener('resize', measure);
    void loadMapData()
      .then((loaded) => {
        data = loaded;
        full = loaded.viewBox;
        europe = loaded.europe;
        view = whole(region === 'europe' ? europe : full, region === 'world');
        initial = view;
      })
      .catch(() => undefined); // offline: the map stays empty until the page is opened again
    return () => window.removeEventListener('resize', measure);
  });

  // All night runs as one path: overlapping edges are not darkened twice (no stripes).
  const night = $derived.by(() => {
    if (nightAt === null) return '';
    return nightRuns(nightAt, 0.5, region === 'world')
      .map((run) => {
        const points: string[] = [];
        const edge = (lat: number, from: number, to: number): void => {
          const steps = Math.max(1, Math.ceil(Math.abs(to - from)));
          for (let i = 0; i <= steps; i++) {
            // Relative longitude without wrapping: runs reach the edge of the world (v0.7).
            const p = projectRelative(lat, from + ((to - from) * i) / steps - CENTRAL_MERIDIAN);
            points.push(`${p.x.toFixed(1)},${(-p.y).toFixed(1)}`);
          }
        };
        // A small overlap closes hairline gaps between neighbouring rows.
        edge(run.lat0 - 0.02, run.lon0, run.lon1);
        edge(run.lat1 + 0.02, run.lon1, run.lon0);
        return `M${points.join('L')}Z`;
      })
      .join('');
  });
  let svg: SVGSVGElement | undefined = $state();
  let pixelWidth = $state(0);
  let pixelHeight = $state(0);
  /** SVG units per screen pixel ("meet": the tighter of both directions; both equal when square). */
  const scale = $derived(
    pixelWidth > 0 && pixelHeight > 0
      ? Math.max(view.w / pixelWidth, view.h / pixelHeight)
      : view.w / 900,
  );
  /** Name in the language of the view (v0.4: English names from Natural Earth). */
  const shown = (place: { name: string; nameEn?: string }): string =>
    i18n.lang === 'en' && place.nameEn ? place.nameEn : place.name;
  /** Country names only where the country is large enough on the screen. */
  const labelMinArea = $derived(1800 * scale * scale);
  const countryFont = $derived(15 * scale);
  const countryLabels = $derived(
    (data?.countries ?? []).flatMap((country) =>
      country.label && country.area >= labelMinArea
        ? [{ id: country.id, name: shown(country), x: country.label[0], y: country.label[1] }]
        : [],
    ),
  );
  const zoomFactor = $derived(side / view.w);

  /** Country names and the zoom buttons (top right): city names keep clear of them, too. */
  function fixedBoxes(): Box[] {
    const countries = countryLabels.map((label) => {
      const half = (Array.from(label.name).length * countryFont * 0.66) / 2;
      return {
        left: label.x - half,
        right: label.x + half,
        top: label.y - countryFont,
        bottom: label.y + countryFont * 0.3,
      };
    });
    const controls = {
      left: view.x + view.w - 64 * scale,
      right: view.x + view.w,
      top: view.y,
      bottom: view.y + 170 * scale,
    };
    return [...countries, controls];
  }

  const cities = $derived.by(() => {
    if (!data) return { dots: [], labels: [] };
    const margin = 20 * scale;
    const dots = data.cities.filter(
      (city) =>
        (city.big || zoomFactor >= MAP.CITY_SMALL_FROM_ZOOM) &&
        city.x >= view.x - margin &&
        city.x <= view.x + view.w + margin &&
        city.y >= view.y - margin &&
        city.y <= view.y + view.h + margin,
    );
    const labels = placeCityLabels(
      dots.map((city) => ({
        key: city.name,
        x: city.x,
        y: city.y,
        text: shown(city),
        fontSize: 13 * scale,
        radius: 3.5 * scale,
      })),
      [...fixedBoxes(), ...(occupied?.(toSvg, scale) ?? [])],
    );
    const names = new Map(labels.map((placed) => [placed.key, placed]));
    return {
      dots,
      labels: dots.flatMap((city) => {
        const placed = names.get(city.name);
        return placed ? [{ name: city.name, text: shown(city), x: placed.x, y: placed.y }] : [];
      }),
    };
  });

  // Fit the known places into view once (v0.2), as soon as map and screen size are known.
  let fitted = false;
  $effect(() => {
    if (fitted || !data || !fit || pixelWidth === 0 || pixelHeight === 0) return;
    fitted = true;
    if (fit.length === 0) return;
    const points = fit.map((place) => toSvg(place.lat, place.lon));
    const xs = points.map((p) => p.x);
    const ys = points.map((p) => p.y);
    const [minX, maxX, minY, maxY] = [
      Math.min(...xs),
      Math.max(...xs),
      Math.min(...ys),
      Math.max(...ys),
    ];
    // Room for markers and their names at the edges (in screen pixels).
    const edge = 90;
    const widthFor = (span: number, pixels: number) =>
      span / Math.max(0.2, 1 - (2 * edge) / Math.max(pixels, 1));
    const w = Math.max(
      side / 12,
      widthFor(maxX - minX, pixelWidth),
      widthFor(maxY - minY, pixelHeight),
    );
    clamp({ x: (minX + maxX) / 2 - w / 2, y: (minY + maxY) / 2 - w / 2, w, h: w });
    initial = view;
  });

  const toSvg = (lat: number, lon: number) => {
    const p = project(lat, lon);
    return { x: p.x, y: -p.y };
  };

  /** Keeps the view inside the frame; where the view is wider than the frame, it is centred. */
  function clamp(next: { x: number; y: number; w: number; h: number }) {
    const w = Math.min(largest.w, Math.max(side / 40, next.w));
    const h = w;
    const inside = (start: number, length: number, from: number, size: number): number =>
      size >= length
        ? from + (length - size) / 2
        : Math.min(from + length - size, Math.max(from, start));
    view = {
      x: inside(next.x, frame[2], frame[0], w),
      y: inside(next.y, frame[3], frame[1], h),
      w,
      h,
    };
  }

  function zoom(factor: number, cx = view.x + view.w / 2, cy = view.y + view.h / 2) {
    const w = view.w * factor;
    const h = view.h * factor;
    clamp({ x: cx - ((cx - view.x) * w) / view.w, y: cy - ((cy - view.y) * h) / view.h, w, h });
  }

  function svgPoint(clientX: number, clientY: number) {
    const matrix = svg?.getScreenCTM();
    if (!svg || !matrix) return null;
    const point = new DOMPoint(clientX, clientY).matrixTransform(matrix.inverse());
    return { x: point.x, y: point.y };
  }

  // Plain Map on purpose: pointer positions are bookkeeping, not rendered state.
  // eslint-disable-next-line svelte/prefer-svelte-reactivity
  const pointers = new Map<number, { x: number; y: number }>();

  function twoPointers(): [{ x: number; y: number }, { x: number; y: number }] | null {
    const [a, b] = [...pointers.values()];
    return a && b ? [a, b] : null;
  }
  let dragDistance = 0;
  let pinchStart = 0;

  function pointerdown(event: PointerEvent) {
    svg?.setPointerCapture(event.pointerId);
    pointers.set(event.pointerId, { x: event.clientX, y: event.clientY });
    dragDistance = 0;
    const pair = twoPointers();
    if (pointers.size === 2 && pair)
      pinchStart = Math.hypot(pair[0].x - pair[1].x, pair[0].y - pair[1].y);
  }

  function pointermove(event: PointerEvent) {
    const previous = pointers.get(event.pointerId);
    if (!previous || !svg) return;
    const rect = svg.getBoundingClientRect();
    if (pointers.size === 2) {
      pointers.set(event.pointerId, { x: event.clientX, y: event.clientY });
      const pair = twoPointers();
      if (!pair) return;
      const [a, b] = pair;
      const distance = Math.hypot(a.x - b.x, a.y - b.y);
      if (pinchStart > 0 && distance > 0) {
        const center = svgPoint((a.x + b.x) / 2, (a.y + b.y) / 2);
        if (center) zoom(pinchStart / distance, center.x, center.y);
        pinchStart = distance;
      }
      dragDistance = Infinity;
      return;
    }
    const dx = event.clientX - previous.x;
    const dy = event.clientY - previous.y;
    dragDistance += Math.hypot(dx, dy);
    pointers.set(event.pointerId, { x: event.clientX, y: event.clientY });
    if (dragDistance > 6) {
      clamp({
        ...view,
        x: view.x - (dx * view.w) / rect.width,
        y: view.y - (dy * view.h) / rect.height,
      });
    }
  }

  function pointerup(event: PointerEvent) {
    const wasTap = pointers.size === 1 && dragDistance <= 6;
    pointers.delete(event.pointerId);
    if (wasTap && onpick) {
      const point = svgPoint(event.clientX, event.clientY);
      if (point) onpick(unproject(point.x, -point.y));
    }
  }

  function wheel(event: WheelEvent) {
    event.preventDefault();
    const point = svgPoint(event.clientX, event.clientY);
    zoom(event.deltaY > 0 ? 1.25 : 0.8, point?.x, point?.y);
  }

  function keydown(event: KeyboardEvent) {
    const step = view.w / 10;
    const moves: Record<string, [number, number]> = {
      ArrowLeft: [-step, 0],
      ArrowRight: [step, 0],
      ArrowUp: [0, -step],
      ArrowDown: [0, step],
    };
    const move = moves[event.key];
    if (move) {
      event.preventDefault();
      clamp({ ...view, x: view.x + move[0], y: view.y + move[1] });
    } else if (event.key === '+' || event.key === '=') zoom(0.8);
    else if (event.key === '-') zoom(1.25);
    else if ((event.key === 'Enter' || event.key === ' ') && onpick) {
      event.preventDefault();
      onpick(unproject(view.x + view.w / 2, -(view.y + view.h / 2)));
    }
  }
</script>

<div class="map" bind:this={wrapper}>
  <!-- The map is an interactive widget (role "application") with full keyboard support:
       arrows pan, +/− zoom, Enter picks the centre. -->
  <!-- svelte-ignore a11y_no_noninteractive_tabindex, a11y_no_noninteractive_element_interactions -->
  <svg
    bind:this={svg}
    bind:clientWidth={pixelWidth}
    bind:clientHeight={pixelHeight}
    viewBox={`${view.x} ${view.y} ${view.w} ${view.h}`}
    role="application"
    aria-label={label}
    tabindex="0"
    onpointerdown={pointerdown}
    onpointermove={pointermove}
    onpointerup={pointerup}
    onpointercancel={(event) => pointers.delete(event.pointerId)}
    onwheel={wheel}
    onkeydown={keydown}
  >
    {#if region === 'world'}
      <!-- v0.7: the sea within the edge of the world; parchment around it. -->
      <rect class="beyond" x={view.x} y={view.y} width={view.w} height={view.h} />
      {#if data}<path class="water" d={data.outline} />{/if}
    {:else}
      <rect class="water" x={full[0]} y={full[1]} width={full[2]} height={full[3]} />
    {/if}
    {#if !data}
      <text class="label" x={view.x + view.w / 2} y={view.y + view.h / 2} font-size={view.w / 30}
        >{t.map.loading}</text
      >
    {/if}
    {#each data?.countries ?? [] as country (country.id)}
      <path class="country" d={country.d} stroke-width={1.2 * scale} />
    {/each}
    {#if data}<path class="lake" d={data.lakes} />{/if}
    {#if night !== ''}
      <path class="night" data-testid="night-layer" d={night} />
    {/if}
    {#each countryLabels as country (country.id)}
      <text class="label" x={country.x} y={country.y} font-size={countryFont}>{country.name}</text>
    {/each}
    <g class="cities" data-testid="map-cities">
      {#each cities.dots as city (city.name)}
        <circle class="city" cx={city.x} cy={city.y} r={3.5 * scale} stroke-width={1.2 * scale} />
      {/each}
      {#each cities.labels as city (city.name)}
        <text class="city-name" x={city.x} y={city.y} font-size={13 * scale}>{city.text}</text>
      {/each}
    </g>
    {@render markers?.(toSvg, scale)}
  </svg>
  <div class="controls">
    <button
      type="button"
      class="button secondary"
      aria-label={t.map.zoomIn}
      onclick={() => zoom(0.7)}>+</button
    >
    <button
      type="button"
      class="button secondary"
      aria-label={t.map.zoomOut}
      onclick={() => zoom(1 / 0.7)}>−</button
    >
    <button
      type="button"
      class="button secondary"
      aria-label={t.map.reset}
      onclick={() => (view = initial ?? largest)}>⤢</button
    >
  </div>
</div>

