<script lang="ts">
  /**
   * Political map (SPEC 12) in parchment style – v0.7 of the whole world; registration and
   * moving (`region="europe"`) stay inside the European section where homes are. Zoom and pan with mouse,
   * touch and buttons; tapping reports the geographic position. No tile server, no foreign
   * hosts (SPEC 12.2). Markers, labels and cities are sized in screen pixels, so they stay
   * readable on small screens (v0.2). Cities: from 1 million inhabitants, from 200 000 when
   * zoomed in; their names give way to the user's own places and owls.
   * v0.8.3: also the map of the bots control centre (same controls); it passes its own language
   * and texts, the app leaves them out.
   * v1.2: the background looks like a hand-drawn historical atlas – warm parchment, fine sepia
   * coasts with ripples in the water, dashed borders, graticule, rivers, hatched mountains,
   * olive groups of trees and the names of seas, rivers, lakes and landscapes in an italic serif,
   * more of them the closer one zooms in (shared/src/map/atlas.ts). Markers, overlays, controls
   * and the projection are unchanged.
   * v1.4.2: smooth on old phones – while dragging, pinching or turning the wheel, the drawn map
   * is only moved and scaled as a whole (CSS transform, at most once per frame); names, symbols
   * and the view itself are worked out once when the gesture ends.
   */
  import { onMount, tick, type Snippet } from 'svelte';
  import { i18n, t } from '../lib/i18n.svelte.ts';
  import { MAP } from '@posteulen/shared/constants.ts';
  import type { Language } from '@posteulen/shared/i18n.ts';
  import type { Texts } from '@posteulen/shared/texts/de.ts';
  import {
    CENTRAL_MERIDIAN,
    project,
    projectRelative,
    unproject,
  } from '@posteulen/shared/map/projection.ts';
  import { placeCityLabels, type Box } from '@posteulen/shared/map/labels.ts';
  import { loadAtlasData, loadMapData, type MapData } from '../lib/map/map-data.ts';
  import {
    GlyphCache,
    glyphPaths,
    overlaps,
    placeAtlasLabels,
    splitName,
    type AtlasData,
  } from '@posteulen/shared/map/atlas.ts';
  import { nightRuns } from '../lib/map/night.ts';

  let {
    onpick,
    markers,
    label,
    lang,
    texts,
    wide = false,
    nightAt = null,
    occupied,
    fit = null,
    region = 'world',
  }: {
    onpick?: (position: { lat: number; lon: number }) => void;
    /** v0.8.3: language and texts of another panel (default: those of the app). */
    lang?: Language;
    texts?: Texts['map'];
    /**
     * v0.8.3: control centre. v0.8.5: as wide as its container, but never taller than the window
     * (wherever it stands on the page), so the page can be scrolled past it.
     */
    wide?: boolean;
    /** Own markers; `scale` is SVG units per screen pixel. */
    markers?: Snippet<[(lat: number, lon: number) => { x: number; y: number }, number]>;
    label?: string;
    /** Draw night areas for this time (SPEC 12.1); null: no day/night layer. */
    nightAt?: number | null;
    /** Space of the own markers and their names; city names keep clear of it. */
    occupied?: (
      toSvg: (lat: number, lon: number) => { x: number; y: number },
      scale: number,
    ) => Box[];
    /** Zoom once, as soon as possible, so that all these places are just visible (v0.2). */
    fit?: readonly { lat: number; lon: number }[] | null;
    /** v0.7: 'europe' keeps zoom and panning inside the European section (pin picking). */
    region?: 'world' | 'europe';
  } = $props();

  const words = $derived(texts ?? t.map);
  const language = $derived(lang ?? i18n.lang);
  const ariaLabel = $derived(label ?? words.label);

  type Frame = readonly [number, number, number, number];
  // Fallback frames until the map data is loaded (as generated by tools/map/build.ts).
  let data = $state<MapData | null>(null);
  /** v1.2: the atlas layer; raw state – the large data never change. */
  let atlas = $state.raw<AtlasData | null>(null);
  const glyphCache = new GlyphCache();
  /** v1.2: ids of the patterns and clip paths, unique per map on the page. */
  const uid = $props.id();
  let full = $state<Frame>([-17243.9, -8392.9, 34487.9, 16785.8]);
  let europe = $state<Frame>([-1801.6, -6984.6, 3020, 2526]);
  const frame = $derived(region === 'europe' ? europe : full);
  /** Zoom levels (cities, automatic zoom, closest zoom) stay those of the European section. */
  const side = $derived(Math.min(europe[2], europe[3]));
  /**
   * v0.4: the map is always square, and so is the view. In the European section it never shows
   * anything beyond its edge (the largest view is the centred square of the shorter side);
   * v0.7: the whole world fits into the square, with parchment above and below.
   */
  function whole(area: Frame, fitAll: boolean) {
    const size = fitAll ? Math.max(area[2], area[3]) : Math.min(area[2], area[3]);
    return {
      x: area[0] + (area[2] - size) / 2,
      y: area[1] + (area[3] - size) / 2,
      w: size,
      h: size,
    };
  }
  const largest = $derived(whole(frame, region === 'world'));
  /**
   * v0.7.1: the view the map opened with (Western Europe when choosing a home, otherwise the
   * automatic zoom on home, contacts and owls); the reset button goes back to it.
   */
  let initial: { x: number; y: number; w: number; h: number } | null = null;
  let view = $state(whole([-17243.9, -8392.9, 34487.9, 16785.8], true));

  /**
   * v0.4: the square map is as large as fits below its position and above a fixed bottom
   * navigation, so the whole map is visible without scrolling (at least 18rem).
   */
  let wrapper: HTMLDivElement | undefined = $state();
  let maxSide = $state<number | null>(null);
  function measure(): void {
    if (!wrapper) return;
    const top = wrapper.getBoundingClientRect().top + window.scrollY;
    const nav = document.querySelector('[data-bottom-nav]')?.getBoundingClientRect().height ?? 0;
    const rem = parseFloat(getComputedStyle(document.documentElement).fontSize) || 16;
    maxSide = wide
      ? Math.max(18 * rem, window.innerHeight - 6 * rem)
      : Math.max(18 * rem, window.innerHeight - top - nav - rem);
  }

  // Through the CSSOM, which the CSP allows (no inline style attribute).
  $effect(() => {
    if (wrapper && maxSide !== null) wrapper.style.setProperty('--map-max', `${maxSide}px`);
  });

  onMount(() => {
    measure();
    window.addEventListener('resize', measure);
    void loadMapData()
      .then((loaded) => {
        data = loaded;
        full = loaded.viewBox;
        europe = loaded.europe;
        view = whole(region === 'europe' ? europe : full, region === 'world');
        initial = view;
      })
      .catch(() => undefined); // offline: the map stays empty until the page is opened again
    void loadAtlasData()
      .then((loaded) => (atlas = loaded))
      .catch(() => undefined); // offline: without the atlas layer
    return () => window.removeEventListener('resize', measure);
  });

  // All night runs as one path: overlapping edges are not darkened twice (no stripes).
  const night = $derived.by(() => {
    if (nightAt === null) return '';
    return nightRuns(nightAt, 0.5, region === 'world')
      .map((run) => {
        const points: string[] = [];
        const edge = (lat: number, from: number, to: number): void => {
          const steps = Math.max(1, Math.ceil(Math.abs(to - from)));
          for (let i = 0; i <= steps; i++) {
            // Relative longitude without wrapping: runs reach the edge of the world (v0.7).
            const p = projectRelative(lat, from + ((to - from) * i) / steps - CENTRAL_MERIDIAN);
            points.push(`${p.x.toFixed(1)},${(-p.y).toFixed(1)}`);
          }
        };
        // A small overlap closes hairline gaps between neighbouring rows.
        edge(run.lat0 - 0.02, run.lon0, run.lon1);
        edge(run.lat1 + 0.02, run.lon1, run.lon0);
        return `M${points.join('L')}Z`;
      })
      .join('');
  });
  let svg: SVGSVGElement | undefined = $state();
  let pixelWidth = $state(0);
  let pixelHeight = $state(0);
  /** SVG units per screen pixel ("meet": the tighter of both directions; both equal when square). */
  const scale = $derived(
    pixelWidth > 0 && pixelHeight > 0
      ? Math.max(view.w / pixelWidth, view.h / pixelHeight)
      : view.w / 900,
  );
  /** Name in the language of the view (v0.4: English names from Natural Earth). */
  const shown = (place: { name: string; nameEn?: string }): string =>
    language === 'en' && place.nameEn ? place.nameEn : place.name;
  /**
   * Country names only where the country is large enough on the screen. v1.2: in widely spaced
   * capitals (atlas style), long names on two lines; the larger country first, no overlaps.
   */
  const labelMinArea = $derived(1800 * scale * scale);
  const countryFont = $derived(13 * scale);
  const countryLabels = $derived.by(() => {
    const placed: { id: string; lines: string[]; x: number; y: number; box: Box }[] = [];
    const marks = occupied?.(toSvg, scale) ?? [];
    const candidates = (data?.countries ?? [])
      .filter((country) => country.label && country.area >= labelMinArea)
      .sort((a, b) => b.area - a.area);
    for (const country of candidates) {
      const [x, y] = country.label ?? [0, 0];
      const lines = splitName(shown(country).toUpperCase(), { c: 'region' });
      const half =
        (Math.max(...lines.map((line) => Array.from(line).length)) * countryFont * 0.8) / 2;
      const box = {
        left: x - half,
        right: x + half,
        top: y - countryFont * (0.6 + 0.55 * lines.length),
        bottom: y + countryFont * (0.55 * lines.length - 0.2),
      };
      if (placed.some((other) => overlaps(box, other.box))) continue;
      // The own places, owls and their names come first.
      if (marks.some((mark) => overlaps(box, mark))) continue;
      placed.push({ id: country.id, lines, x, y, box });
    }
    return placed;
  });
  const zoomFactor = $derived(side / view.w);

  /** Country names and the zoom buttons (top right): city names keep clear of them, too. */
  function fixedBoxes(): Box[] {
    const countries = countryLabels.map((label) => label.box);
    const controls = {
      left: view.x + view.w - 64 * scale,
      right: view.x + view.w,
      top: view.y,
      bottom: view.y + 170 * scale,
    };
    return [...countries, controls];
  }

  /** v1.2: the visible part of the map as a box (for symbols and names of the atlas layer). */
  const viewBox = $derived({
    left: view.x,
    top: view.y,
    right: view.x + view.w,
    bottom: view.y + view.h,
  });
  /**
   * v1.2: the great names of the atlas layer (oceans, seas, the largest ranges and landscapes)
   * are placed before the cities; all others after them, in the space that is left.
   */
  const major = (label: { r: number; c: string }): boolean =>
    label.r === 0 && label.c !== 'river' && label.c !== 'lake';
  const majorNames = $derived.by(() => {
    if (!atlas) return [];
    const fixed = [...fixedBoxes(), ...(occupied?.(toSvg, scale) ?? [])];
    // Oceans first; only they may pass over the dots of island capitals.
    const oceans = placeAtlasLabels(
      atlas.labels,
      viewBox,
      scale,
      language,
      fixed,
      (label) => label.c === 'ocean',
    );
    const others = placeAtlasLabels(
      atlas.labels,
      viewBox,
      scale,
      language,
      [...fixed, ...dotBoxes, ...oceans.map((label) => label.box)],
      (label) => major(label) && label.c !== 'ocean',
    );
    return [...oceans, ...others];
  });

  /** The city dots in view (v1.2: the great atlas names keep clear of them, too). */
  const cityDots = $derived.by(() => {
    if (!data) return [];
    const margin = 20 * scale;
    return data.cities.filter(
      (city) =>
        (city.big || zoomFactor >= MAP.CITY_SMALL_FROM_ZOOM) &&
        city.x >= view.x - margin &&
        city.x <= view.x + view.w + margin &&
        city.y >= view.y - margin &&
        city.y <= view.y + view.h + margin,
    );
  });
  const dotBoxes = $derived(
    cityDots.map((city) => ({
      left: city.x - 5 * scale,
      right: city.x + 5 * scale,
      top: city.y - 5 * scale,
      bottom: city.y + 5 * scale,
    })),
  );

  const cities = $derived.by(() => {
    if (!data) return { dots: [], labels: [] };
    const dots = cityDots;
    const labels = placeCityLabels(
      dots.map((city) => ({
        key: city.name,
        x: city.x,
        y: city.y,
        text: shown(city),
        fontSize: 13 * scale,
        radius: 3.5 * scale,
      })),
      [
        ...fixedBoxes(),
        ...majorNames.map((label) => label.box),
        ...(occupied?.(toSvg, scale) ?? []),
      ],
    );
    const names = new Map(labels.map((placed) => [placed.key, placed]));
    return {
      dots,
      labels: dots.flatMap((city) => {
        const placed = names.get(city.name);
        return placed ? [{ name: city.name, text: shown(city), x: placed.x, y: placed.y }] : [];
      }),
    };
  });

  /** v1.2: all country outlines as one path (coast line and ripples under the land). */
  const land = $derived((data?.countries ?? []).map((country) => country.d).join(''));
  const glyphs = $derived(atlas ? glyphPaths(atlas, glyphCache, viewBox, scale) : null);
  const rivers = $derived((atlas?.rivers ?? []).filter((river) => scale <= river.s));
  /** v1.2: names of seas, rivers, lakes and landscapes – never over cities, countries, markers. */
  const atlasLabels = $derived.by(() => {
    if (!atlas) return [];
    const cityBoxes = [
      ...dotBoxes,
      ...cities.labels.map((city) => {
        const half = (Array.from(city.text).length * 13 * scale * 0.56) / 2;
        return {
          left: city.x - half,
          right: city.x + half,
          top: city.y - 13 * scale,
          bottom: city.y + 4 * scale,
        };
      }),
    ];
    const minor = placeAtlasLabels(
      atlas.labels,
      viewBox,
      scale,
      language,
      [
        ...fixedBoxes(),
        ...majorNames.map((label) => label.box),
        ...cityBoxes,
        ...(occupied?.(toSvg, scale) ?? []),
      ],
      (label) => !major(label),
    );
    return [...majorNames, ...minor];
  });

  /**
   * v1.2: graticule – meridians and parallels every 30° on the whole world, finer when zoomed in
   * (parallels are straight in Equal Earth, meridians curved).
   */
  const graticule = $derived.by(() => {
    if (!data) return '';
    const step =
      view.w > 20000 ? 30 : view.w > 6000 ? 15 : view.w > 2500 ? 10 : view.w > 1000 ? 5 : 2;
    const corners = [
      unproject(view.x, -view.y),
      unproject(view.x + view.w, -view.y),
      unproject(view.x, -(view.y + view.h)),
      unproject(view.x + view.w, -(view.y + view.h)),
      unproject(view.x + view.w / 2, -view.y),
      unproject(view.x + view.w / 2, -(view.y + view.h)),
    ];
    const latTop = Math.min(85, Math.max(...corners.map((c) => c.lat)) + step);
    const latBottom = Math.max(-85, Math.min(...corners.map((c) => c.lat)) - step);
    const relative = corners.map((c) => {
      let delta = c.lon - CENTRAL_MERIDIAN;
      if (delta > 180) delta -= 360;
      if (delta <= -180) delta += 360;
      return delta;
    });
    const wholeWorld = view.w > 6000;
    const lonLeft = wholeWorld ? -180 : Math.max(-180, Math.min(...relative) - step);
    const lonRight = wholeWorld ? 180 : Math.min(180, Math.max(...relative) + step);
    const parts: string[] = [];
    const point = (lat: number, delta: number): string => {
      const p = projectRelative(lat, delta);
      return `${p.x.toFixed(1)} ${(-p.y).toFixed(1)}`;
    };
    for (let lat = Math.ceil(latBottom / step) * step; lat <= latTop; lat += step) {
      parts.push(`M${point(lat, lonLeft)}L${point(lat, lonRight)}`);
    }
    const startLon = Math.ceil((lonLeft + CENTRAL_MERIDIAN) / step) * step - CENTRAL_MERIDIAN;
    for (let delta = startLon; delta <= lonRight; delta += step) {
      const points: string[] = [];
      for (let lat = latBottom; lat <= latTop + 0.01; lat += Math.min(2, step / 2)) {
        points.push(point(Math.min(lat, latTop), delta));
      }
      parts.push(`M${points.join('L')}`);
    }
    return parts.join('');
  });

  // Fit the known places into view once (v0.2), as soon as map and screen size are known.
  let fitted = false;
  $effect(() => {
    if (fitted || !data || !fit || pixelWidth === 0 || pixelHeight === 0) return;
    fitted = true;
    if (fit.length === 0) return;
    const points = fit.map((place) => toSvg(place.lat, place.lon));
    const xs = points.map((p) => p.x);
    const ys = points.map((p) => p.y);
    const [minX, maxX, minY, maxY] = [
      Math.min(...xs),
      Math.max(...xs),
      Math.min(...ys),
      Math.max(...ys),
    ];
    // Room for markers and their names at the edges (in screen pixels).
    const edge = 90;
    const widthFor = (span: number, pixels: number) =>
      span / Math.max(0.2, 1 - (2 * edge) / Math.max(pixels, 1));
    const w = Math.max(
      side / 12,
      widthFor(maxX - minX, pixelWidth),
      widthFor(maxY - minY, pixelHeight),
    );
    view = clamped({ x: (minX + maxX) / 2 - w / 2, y: (minY + maxY) / 2 - w / 2, w, h: w });
    initial = view;
  });

  /** v1.2: fine paper grain (the same noise tile as the paper of the app). */
  const GRAIN = `data:image/svg+xml,${encodeURIComponent(
    "<svg xmlns='http://www.w3.org/2000/svg' width='240' height='240'><filter id='n'><feTurbulence type='fractalNoise' baseFrequency='0.75' numOctaves='3' seed='9'/><feColorMatrix values='0 0 0 0 0.35 0 0 0 0 0.24 0 0 0 0 0.1 0.5 0 0 0 -0.18'/></filter><rect width='100%' height='100%' filter='url(#n)'/></svg>",
  )}`;

  const toSvg = (lat: number, lon: number) => {
    const p = project(lat, lon);
    return { x: p.x, y: -p.y };
  };

  type View = { x: number; y: number; w: number; h: number };

  /** Keeps the view inside the frame; where the view is wider than the frame, it is centred. */
  function clamped(next: View): View {
    const w = Math.min(largest.w, Math.max(side / 40, next.w));
    const h = w;
    const inside = (start: number, length: number, from: number, size: number): number =>
      size >= length
        ? from + (length - size) / 2
        : Math.min(from + length - size, Math.max(from, start));
    return {
      x: inside(next.x, frame[2], frame[0], w),
      y: inside(next.y, frame[3], frame[1], h),
      w,
      h,
    };
  }

  /**
   * v1.4.2: the view during a gesture. The map keeps its drawn state (`view`) and is only moved
   * and scaled as a picture until the gesture ends; then the new view is drawn once.
   */
  let pending: View | null = null;
  /** Position and size of the map on the screen when the gesture began. */
  let gestureRect: DOMRect | null = null;
  let frameRequest = 0;
  let wheelTimer: ReturnType<typeof setTimeout> | undefined;

  const current = (): View => pending ?? view;

  function setView(next: View): void {
    const value = clamped(next);
    if (pending) {
      pending = value;
      frameRequest ||= requestAnimationFrame(paintGesture);
    } else view = value;
  }

  function startGesture(): void {
    if (pending || !svg) return;
    gestureRect = svg.getBoundingClientRect();
    pending = { ...view };
    svg.classList.add('moving');
  }

  /** Screen pixels per SVG unit and the centre of the map on the screen ("meet"). */
  function geometry(rect: DOMRect, shown: View) {
    return {
      k: Math.min(rect.width / shown.w, rect.height / shown.h),
      cx: rect.left + rect.width / 2,
      cy: rect.top + rect.height / 2,
    };
  }

  /** Moves and scales the drawn map so that it shows the pending view (once per frame). */
  function paintGesture(): void {
    frameRequest = 0;
    if (!svg || !pending || !gestureRect) return;
    const { k } = geometry(gestureRect, pending);
    const ratio = view.w / pending.w;
    const tx = (view.x + view.w / 2 - (pending.x + pending.w / 2)) * k;
    const ty = (view.y + view.h / 2 - (pending.y + pending.h / 2)) * k;
    svg.style.transform = `translate(${tx}px, ${ty}px) scale(${ratio})`;
  }

  /** Draws the view of the gesture once, then removes the transform in the same frame. */
  function endGesture(): void {
    if (!pending) return;
    clearTimeout(wheelTimer);
    if (frameRequest) cancelAnimationFrame(frameRequest);
    frameRequest = 0;
    view = pending;
    pending = null;
    gestureRect = null;
    void tick().then(() => {
      if (pending || !svg) return;
      svg.style.transform = '';
      svg.classList.remove('moving');
    });
  }

  function zoom(factor: number, cx?: number, cy?: number) {
    const shown = current();
    const x = cx ?? shown.x + shown.w / 2;
    const y = cy ?? shown.y + shown.h / 2;
    const w = shown.w * factor;
    const h = shown.h * factor;
    setView({ x: x - ((x - shown.x) * w) / shown.w, y: y - ((y - shown.y) * h) / shown.h, w, h });
  }

  /** The SVG position under a point on the screen – during a gesture in its pending view. */
  function svgPoint(clientX: number, clientY: number) {
    if (!svg) return null;
    const shown = current();
    const { k, cx, cy } = geometry(gestureRect ?? svg.getBoundingClientRect(), shown);
    if (!(k > 0)) return null;
    return {
      x: shown.x + shown.w / 2 + (clientX - cx) / k,
      y: shown.y + shown.h / 2 + (clientY - cy) / k,
    };
  }

  // Plain Map on purpose: pointer positions are bookkeeping, not rendered state.
  // eslint-disable-next-line svelte/prefer-svelte-reactivity
  const pointers = new Map<number, { x: number; y: number }>();

  function twoPointers(): [{ x: number; y: number }, { x: number; y: number }] | null {
    const [a, b] = [...pointers.values()];
    return a && b ? [a, b] : null;
  }
  let dragDistance = 0;
  let pinchStart = 0;

  function pointerdown(event: PointerEvent) {
    svg?.setPointerCapture(event.pointerId);
    pointers.set(event.pointerId, { x: event.clientX, y: event.clientY });
    dragDistance = 0;
    const pair = twoPointers();
    if (pointers.size === 2 && pair)
      pinchStart = Math.hypot(pair[0].x - pair[1].x, pair[0].y - pair[1].y);
  }

  function pointermove(event: PointerEvent) {
    const previous = pointers.get(event.pointerId);
    if (!previous || !svg) return;
    if (pointers.size === 2) {
      pointers.set(event.pointerId, { x: event.clientX, y: event.clientY });
      const pair = twoPointers();
      if (!pair) return;
      startGesture();
      const [a, b] = pair;
      const distance = Math.hypot(a.x - b.x, a.y - b.y);
      if (pinchStart > 0 && distance > 0) {
        const center = svgPoint((a.x + b.x) / 2, (a.y + b.y) / 2);
        if (center) zoom(pinchStart / distance, center.x, center.y);
        pinchStart = distance;
      }
      dragDistance = Infinity;
      return;
    }
    const dx = event.clientX - previous.x;
    const dy = event.clientY - previous.y;
    dragDistance += Math.hypot(dx, dy);
    pointers.set(event.pointerId, { x: event.clientX, y: event.clientY });
    if (dragDistance > 6) {
      startGesture();
      const shown = current();
      const { k } = geometry(gestureRect ?? svg.getBoundingClientRect(), shown);
      if (k > 0) setView({ ...shown, x: shown.x - dx / k, y: shown.y - dy / k });
    }
  }

  function pointerup(event: PointerEvent) {
    const wasTap = pointers.size === 1 && dragDistance <= 6;
    pointers.delete(event.pointerId);
    if (pointers.size === 0) endGesture();
    if (wasTap && onpick) {
      const point = svgPoint(event.clientX, event.clientY);
      if (point) onpick(unproject(point.x, -point.y));
    }
  }

  function pointercancel(event: PointerEvent) {
    pointers.delete(event.pointerId);
    if (pointers.size === 0) endGesture();
  }

  function wheel(event: WheelEvent) {
    // v0.8.5: zoomed out as far as it goes, the wheel scrolls the page instead.
    if (event.deltaY > 0 && current().w >= largest.w) return;
    event.preventDefault();
    startGesture();
    const point = svgPoint(event.clientX, event.clientY);
    zoom(event.deltaY > 0 ? 1.25 : 0.8, point?.x, point?.y);
    // A burst of wheel steps is one gesture: drawn once it has been quiet for a moment.
    clearTimeout(wheelTimer);
    wheelTimer = setTimeout(endGesture, 180);
  }

  function keydown(event: KeyboardEvent) {
    endGesture();
    const step = view.w / 10;
    const moves: Record<string, [number, number]> = {
      ArrowLeft: [-step, 0],
      ArrowRight: [step, 0],
      ArrowUp: [0, -step],
      ArrowDown: [0, step],
    };
    const move = moves[event.key];
    if (move) {
      event.preventDefault();
      setView({ ...view, x: view.x + move[0], y: view.y + move[1] });
    } else if (event.key === '+' || event.key === '=') zoom(0.8);
    else if (event.key === '-') zoom(1.25);
    else if ((event.key === 'Enter' || event.key === ' ') && onpick) {
      event.preventDefault();
      onpick(unproject(view.x + view.w / 2, -(view.y + view.h / 2)));
    }
  }
</script>

